-- Run once in the Supabase SQL editor before starting the API.
-- The API never creates tables itself, so this script is what enables
-- Row Level Security on the table that Supabase exposes through its Data API.

create table if not exists products (
  id bigint generated by default as identity primary key,
  name text not null,
  price numeric not null,
  stock integer not null default 0,
  image_url text,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

alter table products enable row level security;

create policy "Anyone can read products" on products for select to public using (true);
