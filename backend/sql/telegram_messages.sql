-- Conversation memory of the Telegram bot. Run once in the Supabase SQL editor
-- (like schema.sql). It is idempotent, so running it again changes nothing.
-- The API never creates tables itself. Until this script has run, the bot keeps
-- answering questions, just without remembering earlier messages.
--
-- The bot keeps only the last 10 messages of each chat (it prunes on every
-- write) and /olvidar deletes a chat's rows. Messages are stored as text, so the
-- table holds what users write to the bot.

create table if not exists telegram_messages (
  id bigint generated by default as identity primary key,
  chat_id bigint not null,
  role text not null check (role in ('user', 'assistant')),
  content text not null,
  created_at timestamptz not null default now()
);

create index if not exists telegram_messages_chat_id_id_idx
  on telegram_messages (chat_id, id);

-- Row Level Security is ON and there are deliberately NO policies. Supabase
-- exposes the `public` schema through its Data API, and with RLS enabled but no
-- policy that API can neither read nor write this table (it hides everything,
-- unlike schema.sql's products table, which has a public read policy). The
-- backend connects with a database role that bypasses RLS, so it is not affected.
alter table telegram_messages enable row level security;
